// Generates TypeScript types from the public OpenAPI documents of the developer
// docs (the same files as https://developer.omaxtelecom.com/openapi/*.json).
//
//   npm run generate                      # reads ../developer-docs/dist/openapi
//   OMAX_OPENAPI_DIR=/path npm run generate
//
// Build the docs first (cd ../developer-docs && npm run build) so dist/ is current.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = process.env.OMAX_OPENAPI_DIR ?? path.join(root, "../developer-docs/dist/openapi");
const target = path.join(root, "src/generated");

const specs = {
  sms: "sms.json",
  "phone-numbers": "phone-numbers.json",
  webhooks: "webhooks.json",
};

mkdirSync(target, { recursive: true });

for (const [name, file] of Object.entries(specs)) {
  const input = path.join(source, file);
  if (!existsSync(input)) {
    throw new Error(`${input} not found. Build the developer docs first, or set OMAX_OPENAPI_DIR.`);
  }
  const spec = JSON.parse(readFileSync(input, "utf8"));
  const ast = await openapiTS(spec, { alphabetize: false, exportType: true });
  const banner = `// Generated by scripts/generate.mjs from ${file} (${spec.info?.title ?? name} ${spec.info?.version ?? ""}). Do not edit.\n\n`;
  writeFileSync(path.join(target, `${name}.ts`), banner + astToString(ast));
  console.log(`✓ src/generated/${name}.ts`);
}
